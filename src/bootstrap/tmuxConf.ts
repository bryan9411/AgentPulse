import {join} from 'node:path';
import {DEFAULT_LANG, strings, type Lang} from '../i18n/strings.ts';
import {COLORS} from '../ui/theme.ts';

// tmux asks the outer terminal for extended keys with modifyOtherKeys only.
// iTerm2 3.4 ignores that and reports Shift+Enter as a bare \r, while it does
// honour the kitty keyboard protocol that Claude Code uses when run directly
// (M7). Ask for both: a terminal ignores the request it does not know.
const EXTENDED_KEYS_OVERRIDE = String.raw`set -as terminal-overrides ',*:Eneks=\E[>4;2m\E[>1u:Dseks=\E[>4m\E[<u'`;

// Shared by both servers: no prefix, no default prefix-table bindings, no
// escape delay (Esc must reach the AI at once), true colour and extended keys
// so Shift+Enter survives the nested client (M0 G2).
const COMMON = `
set -g prefix None
set -g prefix2 None
unbind-key -a -T prefix
set -s escape-time 0
set -s focus-events on
set -s extended-keys on
set -s extended-keys-format csi-u
set -g default-terminal "tmux-256color"
set -as terminal-features ",*:RGB"
set -as terminal-features ",*:extkeys"
${EXTENDED_KEYS_OVERRIDE}
set -g mouse on
`;

export function uiTmuxConf(): string {
	const c = COLORS;
	return `# Generated by AgentPulse. Rewritten on every launch; edits are lost.
${COMMON}
set -g status on
set -g status-position top
set -g status-interval 0
set -g status-style "bg=${c.bg},fg=${c.dim}"
set -g status-format[0] " AgentPulse"
set -g window-style "bg=${c.bg},fg=${c.text}"
set -g window-active-style "bg=${c.bg},fg=${c.text}"
set -g pane-border-style "fg=${c.rule},bg=${c.bg}"
set -g pane-active-border-style "fg=${c.dim},bg=${c.bg}"
set -g pane-border-status top
set -g pane-border-format "#{?@ap-label, #{@ap-label} ,}"
set -g pane-border-lines single
set -g pane-border-indicators off
set -g message-style "bg=${c.selected},fg=${c.text}"
# -q: these options arrived after tmux 3.2, the oldest version supported.
set -gq popup-style "bg=${c.bg},fg=${c.text}"
set -gq popup-border-style "fg=${c.dim},bg=${c.bg}"
set -gq popup-border-lines single
`;
}

export function confPaths(dir: string): {ui: string; agents: string} {
	return {ui: join(dir, 'ui.tmux.conf'), agents: join(dir, 'agents.tmux.conf')};
}

// The exit line must make it obvious the AI is gone: users press ctrl+c to
// leave and the leftover screen can look like a hang (M0 notes).
export function exitedFormat(lang: Lang = DEFAULT_LANG): string {
	return `#[fg=${COLORS.text},bg=${COLORS.selected}] ${strings(lang).tmux.exited('#{pane_dead_status}')} #[default]`;
}

export function agentsTmuxConf(lang: Lang = DEFAULT_LANG): string {
	return `# Generated by AgentPulse. Rewritten on every launch; edits are lost.
${COMMON}
set -g status off
set -g history-limit 50000
set -g remain-on-exit on
set -g remain-on-exit-format "${exitedFormat(lang)}"
# Closing the session on screen switches the embedded client to another one
# instead of detaching it.
set -g detach-on-destroy off
set -g window-size latest
set -g allow-passthrough on
set -s set-clipboard on
set-environment -g COLORTERM truecolor
`;
}
